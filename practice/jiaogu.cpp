#include <iostream>
using namespace std;

// 角谷猜想（Collatz / 3n+1 问题）：
// 对正整数 a：奇数则变为 3a+1，偶数则除以 2，反复操作直到变为 1。
// 本程序在演算过程中统计并输出若干信息。
int main()
{
	// a：当前数值
	// sum：总操作步数（奇变换 + 偶变换）
	// m：奇数步次数（执行 3a+1 的次数）
	// n：偶数步次数（执行 a/2 的次数）
	// x：当前连续“除以 2”的次数
	// max2：历史上连续“除以 2”的最大次数
	int a, sum = 0, m = 0, n = 0, x = 0, max2 = 0;

	cin >> a;          // 读入起始正整数
	int max1 = a;      // max1：演算过程中出现过的最大数（含初始值）

	// 当 a 变为 1 时停止（角谷猜想认为最终会到达 1）
	while (a > 1)
	{
		sum++;                 // 本轮算一步
		cout << sum << " ";    // 输出当前是第几步

		if (a % 2 == 1)        // 奇数：执行 3a+1
		{
			m++;               // 奇数步 +1
			x = 0;             // 连续除 2 被打断，清零
			cout << a << " * 3 + 1 = ";
			a = a * 3 + 1;
		}
		else                   // 偶数：执行 a/2
		{
			n++;               // 偶数步 +1
			x++;               // 连续除 2 次数 +1
			if (x > max2)      // 更新“最长连续除 2”
				max2 = x;
			cout << a << " / 2 = ";
			a /= 2;
		}

		cout << a << endl;     // 输出本步运算后的结果
		if (a > max1)          // 更新过程最大值
			max1 = a;
	}

	// 最终一行输出四个统计量：
	// m：奇数步次数
	// n：偶数步次数
	// max1：过程中出现的最大数
	// max2：最长连续除以 2 的次数
	cout << m << " " << n << " " << max1 << " " << max2;
	return 0;
}
